// =====================================================================
// あなた専用のリプ生成プロンプト
//
// 「AIリプ」ボタンを押すと、このテンプレートに投稿者名と投稿本文を
// 埋め込んだプロンプトが自動で作られ、ChatGPT に渡されます。
//
// 文言を調整したいときは、このファイルだけを編集すれば OK です。
// （編集後は chrome://extensions で拡張機能を更新 → X を再読み込み）
// =====================================================================

function buildPrompt(info) {
  const author = info.author || "（不明）";
  const text = info.text || "";

  return `あなたはX（旧Twitter）の交流リプライを作るアシスタントです。
最後に示す投稿への返信を3案作ってください。

## 禁止事項
- 投稿本文の要約はしない
- 「参考になります」「勉強になります」「共感しました」は使わない

## 視点の優先順位（最初に当てはまるものを1つ選び、3案すべてに適用）
1. 投稿で不足している具体例
2. 初心者が知りたいこと
3. 実践時の注意点
4. 判断基準
5. 例外ケース

## 3案の形式
- 本命: 丁寧に一歩踏み込む質問。投稿者が答えたくなるもの
- 親しみ: カジュアルで温かい文体。絵文字を1つ入れる
- 知見: 自分の見解や経験を一言添えたうえでの深掘り

## 条件
- それぞれ140文字以内の自然な日本語
- 投稿の具体的な内容（キーワード）に触れて、定型文にしない
- 「本命」「親しみ」「知見」のラベルを付けて出力する

---
投稿者: ${author}
投稿本文:
${text}`;
}
