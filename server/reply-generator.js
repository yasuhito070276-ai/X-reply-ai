// =====================================================================
// リプ生成ロジック（ルールベース版）
//
// 投稿本文を解析して「読者が次に知りたいこと」を補足する
// リプを3案（本命・親しみ・知見）生成します。
//
// ルール:
//   ・本文の要約はしない
//   ・「参考になります」「勉強になります」「共感しました」は使わない
//
// 視点の優先順位:
//   1. 投稿に不足している具体例
//   2. 初心者が知りたいこと
//   3. 実践するときの注意点
//   4. 判断基準
//   5. 例外ケース
//
// このファイルは server.js から読み込まれ、
// generateReplies() という関数を提供します。
// 将来 OpenAI API に切り替えるときは、server.js がこの関数の代わりに
// AI を呼ぶようにするだけで済みます。
// =====================================================================

// ---- 禁止ワード ------------------------------------------------------
// 万一テンプレートに紛れ込んでも検知できるよう、明示的に持っておきます
const BANNED_PHRASES = ["参考になります", "勉強になります", "共感しました"];

// =====================================================================
// 1. 投稿の解析
// =====================================================================

// 話題のキーワードとしては意味が薄い、ありふれた言葉のリスト。
// これを除外しないと「ポイントを始める初心者は…」のような
// 不自然な文ができてしまう。
const GENERIC_WORDS = [
  "ポイント", "コツ", "オススメ", "タイミング", "メリット", "デメリット",
  "ステップ", "ケース", "パターン", "ルール", "レベル", "バランス",
  "シンプル", "リアル", "ベスト", "ヤバイ", "ダメ", "スタート",
];

// 投稿本文から「話題のキーワード」を1つ抜き出す
// （リプの文中に埋め込んで、具体的な返信に見せるため）
function extractTopic(text) {
  // 優先1: 「」で囲まれた言葉（投稿者が強調したいキーワードのことが多い）
  const quoted = text.match(/「([^」]{2,15})」/);
  if (quoted && !GENERIC_WORDS.includes(quoted[1])) return quoted[1];

  // 優先2: 英数字の単語（ツール名・サービス名など。例: ChatGPT, Notion）
  const alphaList = text.match(/[A-Za-z][A-Za-z0-9.+#-]{2,}/g) || [];
  for (const word of alphaList) {
    if (!GENERIC_WORDS.includes(word)) return word;
  }

  // 優先3: 4文字以上のカタカナ語（例: マーケティング、ダイエット）
  const katakanaList = text.match(/[ァ-ヴー]{4,}/g) || [];
  for (const word of katakanaList) {
    if (!GENERIC_WORDS.includes(word)) return word;
  }

  // 見つからなければ空文字（テンプレート側で「これ」などに置き換える）
  return "";
}

// 投稿の特徴を調べるためのパターン集
const FEATURE_PATTERNS = {
  // 具体例がすでに含まれているか
  // （「例えば」などの言葉や、「3万円」「5分」のような具体的な数値）
  hasExample:
    /例えば|たとえば|具体的に|実際に|事例|ケース|\d+(?:円|万|億|%|割|分|時間|日|年|週間|ヶ月|か月|回|件|人|個|kg|キロ)/,

  // やり方・ノウハウ系の投稿か → 実践時の注意点を知りたいはず
  isHowTo: /方法|やり方|コツ|手順|ステップ|するには|すべき|した方が|したほうが|おすすめ|大事|大切|ポイント|習慣/,

  // 比較・選択系の投稿か → 判断基準を知りたいはず
  isComparison: /より|比べ|くらべ|どっち|どちら|vs|選び方|選ぶ|派/,
};

// =====================================================================
// 2. 視点の決定（優先順位の順に判定し、最初に当てはまったものを採用）
// =====================================================================

function decideAngle(text, topic) {
  // 優先1: 具体例が見当たらない → 具体例を尋ねる
  if (!FEATURE_PATTERNS.hasExample.test(text)) return "example";

  // 優先2: ツール名・専門用語っぽいキーワード（英単語・カタカナ語）が
  //         話題の中心 → 初心者が知りたいこと（始め方）を尋ねる
  if (topic && /^(?:[A-Za-z]|[ァ-ヴー])/.test(topic)) return "beginner";

  // 優先3: ノウハウ系 → 実践時の注意点を尋ねる
  if (FEATURE_PATTERNS.isHowTo.test(text)) return "caution";

  // 優先4: 比較系 → 判断基準を尋ねる
  if (FEATURE_PATTERNS.isComparison.test(text)) return "criteria";

  // 優先5: どれにも当てはまらない → 例外ケースを尋ねる
  return "exception";
}

// パネルに表示する視点の名前
const ANGLE_NAMES = {
  example: "① 不足している具体例",
  beginner: "② 初心者が知りたいこと",
  caution: "③ 実践するときの注意点",
  criteria: "④ 判断基準",
  exception: "⑤ 例外ケース",
};

// =====================================================================
// 3. 3案の生成（視点ごとに 本命・親しみ・知見 のテンプレート）
//
// topic には extractTopic() で抜き出したキーワードが入ります。
// キーワードが取れなかった場合に備えて、各関数の先頭で
// 代わりの言葉（「これ」「この内容」）を用意しています。
// =====================================================================

const REPLY_TEMPLATES = {
  // --- 優先1: 不足している具体例を尋ねる ---
  example: (topic) => {
    const t = topic || "これ";
    return {
      本命: `${t}について、実際の具体例もぜひ知りたいです。どんな場面で一番効果がありましたか？`,
      親しみ: `これ気になります！${t}って、例えばどんなふうにやっているんですか？😊`,
      知見: `${t}は場面によって使い方が変わる印象があります。特に効果が出た実例があれば、多くの人のヒントになりそうです！`,
    };
  },

  // --- 優先2: 初心者が知りたいこと（始め方）を尋ねる ---
  beginner: (topic) => {
    const t = topic || "これ";
    return {
      本命: `${t}をこれから始める初心者は、まず何から手を付けるのが良いでしょうか？`,
      親しみ: `初心者質問ですみません🙏 ${t}って、最初はどこから始めるのがおすすめですか？`,
      知見: `${t}は最初の一歩でつまずく人が多い印象です。初心者向けの入り口をどう設計されているか気になります！`,
    };
  },

  // --- 優先3: 実践するときの注意点を尋ねる ---
  caution: (topic) => {
    const t = topic || "これ";
    return {
      本命: `実践するときに気をつけるべき点はありますか？やりがちな失敗があれば事前に知っておきたいです。`,
      親しみ: `さっそく試してみたいです！${t}を初めてやるときの注意点ってありますか？😳`,
      知見: `実際にやってみると細かい落とし穴がありそうですね。事前に知っておくべき注意点があれば、失敗を減らせる人が多そうです。`,
    };
  },

  // --- 優先4: 判断基準を尋ねる ---
  criteria: (topic) => {
    const t = topic || "どちら";
    return {
      本命: `${t}を選ぶか迷ったとき、判断基準はどこに置くのが良いでしょうか？`,
      親しみ: `迷っちゃいますね…！ズバリ、選ぶときの決め手って何ですか？`,
      知見: `状況によって最適解が変わりそうなテーマですね。判断の分かれ目になる基準があれば知りたいです。`,
    };
  },

  // --- 優先5: 例外ケースを尋ねる ---
  exception: (topic) => {
    const t = topic || "これ";
    return {
      本命: `${t}が当てはまらない例外的なケースはありますか？逆のパターンも気になります。`,
      親しみ: `なるほど…！ちなみに${t}って、うまくいかないケースもあるんですか？🤔`,
      知見: `多くの場合はこの通りだと思う一方で、例外もありそうですね。当てはまらない条件があれば知りたいです。`,
    };
  },
};

// =====================================================================
// メインの関数（content.js から呼ばれる）
//
// 入力: { author: 投稿者名, text: 投稿本文 }
// 出力: {
//   angleName: 採用した視点の名前（パネルに表示する）,
//   replies:  [{ label: "本命", text: "..." }, ...] の3件
// }
// =====================================================================

function generateReplies(info) {
  const text = info.text || "";

  // 1. 解析
  const topic = extractTopic(text);

  // 2. 視点の決定
  const angle = decideAngle(text, topic);

  // 3. 3案の生成
  const drafts = REPLY_TEMPLATES[angle](topic);

  const replies = Object.entries(drafts).map(([label, replyText]) => {
    // 禁止ワードが紛れ込んでいないか最終チェック（安全網）
    for (const banned of BANNED_PHRASES) {
      if (replyText.includes(banned)) {
        console.warn(`[AIリプ] 禁止ワード「${banned}」を検出しました:`, replyText);
      }
    }
    return { label, text: replyText };
  });

  // 動作確認用ログ（開発者ツールの Console で確認できます）
  console.log("[AIリプ] 解析結果:", { topic, angle, angleName: ANGLE_NAMES[angle] });

  return { angleName: ANGLE_NAMES[angle], replies };
}

// server.js から generateReplies() を使えるようにする
module.exports = { generateReplies };
